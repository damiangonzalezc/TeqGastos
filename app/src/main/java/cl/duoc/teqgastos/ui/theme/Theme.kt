/** Acceso a tokens propios de la app que Material no trae (paleta de estados). */
object TeqTheme {
    val estados: PaletaEstados
        @Composable @ReadOnlyComposable
        get() = LocalPaletaEstados.current
}

@Composable
fun TeqGastosTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    CompositionLocalProvider(
        LocalPaletaEstados provides if (darkTheme) PaletaEstadosOscura else PaletaEstadosClara
    ) {
        MaterialTheme(
            colorScheme = if (darkTheme) EsquemaOscuro else EsquemaClaro,
            typography = Tipografia,
            content = content
        )
    }
}
